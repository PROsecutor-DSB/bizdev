def build() -> tuple[list[dict], dict[str, str]]:
    posts: list[dict] = []
    labels: dict[str, str] = {}
    pid = 1000
    day = 0

    def add(text: str, day_offset: int, label: str = "OTHER", **kw) -> None:
        nonlocal pid
        pid += 1
        labels[f"{CHANNEL}/{pid}"] = label
        dt = START + timedelta(days=day_offset, minutes=kw.pop("minutes", 0))
        posts.append(
            {
                "channel": CHANNEL,
                "post_id": pid,
                "permanent_url": f"https://t.me/{CHANNEL}/{pid}",
                "date": dt.isoformat(),
                "raw_text": text,
                "text_html_links": kw.pop("html_links", []),
                "views": kw.pop("views", 5000 + (pid % 47) * 180),
                "reactions": kw.pop("reactions", {"🔥": pid % 60, "👍": pid % 23}),
                "forwarded_from": kw.pop("forwarded_from", None),
                "forwarded_from_url": None,
                "reply_to": kw.pop("reply_to", None),
                "reply_to_url": None,
                "has_image": kw.pop("has_image", False),
                "image_count": 0,
                "has_video": False,
                "has_document": False,
                "has_poll": False,
                "has_sticker": False,
                "link_preview": None,
                "source": "synthetic_fixture",
                "scraped_at": "2026-09-18T00:00:00+00:00",
            }
        )

    # interleave categories across four years
    pools = [
        (CONTENT, 7, "CONTENT"), (CONTENT_PLUS_PROMO, 23, "CONTENT_PLUS_PROMO"),
        (PROMO, 11, "PROMO"), (HIRING, 61, "HIRING"), (PERSONAL, 41, "PERSONAL"),
        (CASE, 29, "CASE"), (NEWS, 37, "NEWS"),
    ]
    for pool, stride, label in pools:
        for i, text in enumerate(pool):
            add(text, day + i * stride, label)
        day += 3

    for offset, text in EVOLVING:
        add(text, offset + 5, "CONTENT")

    # a real multi-post thread, minutes apart
    base_day = 400
    for i, text in enumerate(THREAD):
        add(text, base_day, "CONTENT", minutes=i * 4)

    # media-only post, and an exact repeat of an earlier announcement
    add("", 410, "OTHER", has_image=True)
    add(PROMO[0], 415, "PROMO")

    # one very long post to exercise chunking
    add("\n\n".join(CONTENT[:6]) + "\n\n" + "\n\n".join(CONTENT[6:12]), 420, "CONTENT")

    posts.sort(key=lambda p: p["post_id"])
    return posts, labels


def main() -> int:
    posts, labels = build()
    out = RAW_DIR / f"{CHANNEL}.raw.jsonl"
    write_jsonl(out, posts)
    # ground truth for tests/test_pipeline_e2e.py
    write_jsonl(
        Path(__file__).parent / "fixtures" / "demo_channel.labels.jsonl",
        [{"post_uid": k, "category": v} for k, v in sorted(labels.items())],
    )
    print(f"wrote {len(posts)} SYNTHETIC posts -> {out}")
    print("!! synthetic test data, not a real channel archive !!")
    return 0


